from dataclasses import dataclass
from datetime import datetime
from typing import Any

from .monitoring_schema import MonitoringSchema


@dataclass(frozen=True)
class MonitoringDataset:
    """
    Dataset used to evaluate a deployed model.

    The dataset is built from the monitoring tables produced by dbt.
    Each observation contains the feature values, the prediction
    generated by the deployed model and the associated ground truth.

    The MonitoringSchema describes the semantic meaning of the columns,
    allowing the dataset to be consumed by different monitoring
    frameworks such as Evidently.
    """

    model_name: str

    model_version: str

    feature_set_version: str

    period_start: datetime

    period_end: datetime

    schema: MonitoringSchema

    observations: list[dict[str, Any]]